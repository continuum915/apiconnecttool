using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace ApiConnectTool.Tests.Architecture;

internal sealed record SourceFile(string Path, string Text);

/// <summary>
/// Measures hand-written C# types in logical lines: lines that are neither blank nor only a
/// comment. Types are keyed by namespace and type name; partial declarations are summed.
/// </summary>
internal static class TypeSizeMeasurement
{
    private const string SolutionFileName = "ApiConnectTool.slnx";
    private const string AppProjectDirectory = "ApiConnectTool";
    private static readonly string[] GeneratedSuffixes = [".g.cs", ".g.i.cs", ".designer.cs", ".generated.cs"];

    /// <summary>
    /// Measures every hand-written type in the app project, located by walking up from the test
    /// output directory to the solution file.
    /// </summary>
    public static IReadOnlyDictionary<string, int> MeasureAppProject()
    {
        var projectDirectory = Path.Combine(FindRepositoryRoot(AppContext.BaseDirectory), AppProjectDirectory);
        var files = Directory.EnumerateFiles(projectDirectory, "*.cs", SearchOption.AllDirectories)
            .Select(path => new SourceFile(
                Path.GetRelativePath(projectDirectory, path),
                File.ReadAllText(path)))
            .Where(IsHandWritten);
        return Measure(files);
    }

    private static string FindRepositoryRoot(string startDirectory)
    {
        for (var directory = new DirectoryInfo(startDirectory); directory is not null; directory = directory.Parent)
        {
            if (File.Exists(Path.Combine(directory.FullName, SolutionFileName)))
            {
                return directory.FullName;
            }
        }

        throw new InvalidOperationException(
            $"Could not find {SolutionFileName} in '{startDirectory}' or any parent directory.");
    }

    public static IReadOnlyDictionary<string, int> Measure(IEnumerable<SourceFile> files)
    {
        var sizes = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var file in files)
        {
            var tree = CSharpSyntaxTree.ParseText(file.Text, path: file.Path);
            var root = tree.GetRoot();
            var text = tree.GetText();
            var isLogicalLine = LogicalLineMask(root, text);

            foreach (var type in TopLevelTypes(root))
            {
                var span = text.Lines.GetLinePositionSpan(type.Span);
                var count = 0;
                for (var line = span.Start.Line; line <= span.End.Line; line++)
                {
                    if (isLogicalLine[line])
                    {
                        count++;
                    }
                }

                var name = QualifiedName(type);
                sizes[name] = sizes.GetValueOrDefault(name) + count;
            }
        }

        return sizes;
    }

    /// <summary>
    /// True for hand-written C# source. Build output under <c>bin</c> or <c>obj</c>, generated
    /// files, and markup are excluded. <paramref name="file"/>'s path is relative to the project.
    /// </summary>
    public static bool IsHandWritten(SourceFile file)
    {
        var segments = file.Path.Split('/', '\\');
        if (segments.Any(segment => segment.Equals("bin", StringComparison.OrdinalIgnoreCase) ||
                                    segment.Equals("obj", StringComparison.OrdinalIgnoreCase)))
        {
            return false;
        }

        var fileName = segments[^1];
        if (!fileName.EndsWith(".cs", StringComparison.OrdinalIgnoreCase) ||
            GeneratedSuffixes.Any(suffix => fileName.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)))
        {
            return false;
        }

        return !HasAutoGeneratedHeader(file.Text);
    }

    private static bool HasAutoGeneratedHeader(string text)
    {
        var root = CSharpSyntaxTree.ParseText(text).GetRoot();
        return root.GetLeadingTrivia()
            .Where(IsComment)
            .Any(trivia => trivia.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));
    }

    private static bool[] LogicalLineMask(SyntaxNode root, SourceText text)
    {
        var inComment = new bool[text.Length];
        foreach (var trivia in root.DescendantTrivia(descendIntoTrivia: true))
        {
            if (IsComment(trivia))
            {
                for (var i = trivia.FullSpan.Start; i < trivia.FullSpan.End; i++)
                {
                    inComment[i] = true;
                }
            }
        }

        var logical = new bool[text.Lines.Count];
        foreach (var line in text.Lines)
        {
            for (var i = line.Start; i < line.End; i++)
            {
                if (!char.IsWhiteSpace(text[i]) && !inComment[i])
                {
                    logical[line.LineNumber] = true;
                    break;
                }
            }
        }

        return logical;
    }

    private static bool IsComment(SyntaxTrivia trivia) => trivia.Kind() is
        SyntaxKind.SingleLineCommentTrivia or
        SyntaxKind.MultiLineCommentTrivia or
        SyntaxKind.SingleLineDocumentationCommentTrivia or
        SyntaxKind.MultiLineDocumentationCommentTrivia;

    private static IEnumerable<MemberDeclarationSyntax> TopLevelTypes(SyntaxNode root) =>
        root.DescendantNodes(node => node is CompilationUnitSyntax or BaseNamespaceDeclarationSyntax)
            .OfType<MemberDeclarationSyntax>()
            .Where(node => node is BaseTypeDeclarationSyntax or DelegateDeclarationSyntax);

    private static string QualifiedName(MemberDeclarationSyntax type)
    {
        var (identifier, arity) = type switch
        {
            TypeDeclarationSyntax t => (t.Identifier.Text, t.Arity),
            BaseTypeDeclarationSyntax t => (t.Identifier.Text, 0),
            DelegateDeclarationSyntax d => (d.Identifier.Text, d.Arity),
            _ => throw new ArgumentOutOfRangeException(nameof(type)),
        };
        var name = arity == 0 ? identifier : $"{identifier}`{arity}";

        var namespaces = type.Ancestors()
            .OfType<BaseNamespaceDeclarationSyntax>()
            .Select(ns => ns.Name.ToString())
            .Reverse();
        var prefix = string.Join(".", namespaces);
        return prefix.Length == 0 ? name : $"{prefix}.{name}";
    }
}
