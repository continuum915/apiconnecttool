using Xunit;

namespace ApiConnectTool.Tests.Architecture;

public class TypeSizeMeasurementTests
{
    [Fact]
    public void Measure_BlankAndCommentOnlyLines_AreNotCounted()
    {
        const string source = """
            namespace ApiConnectTool.Sample;

            /// <summary>
            /// Documented.
            /// </summary>
            public class Widget
            {
                // A line comment.

                /*
                 * Inside a block comment.
                 */
                public int Value { get; set; } // trailing comment still counts

                /** Doc block. */
                public void Run() { }
            }
            """;

        var sizes = TypeSizeMeasurement.Measure([new SourceFile("Widget.cs", source)]);

        Assert.Equal(5, sizes["ApiConnectTool.Sample.Widget"]);
    }

    [Fact]
    public void Measure_PartialTypeAcrossFiles_IsSummedIntoOneTotal()
    {
        const string first = """
            namespace ApiConnectTool.Sample;

            public partial class Widget
            {
                public int A;
            }
            """;
        const string second = """
            namespace ApiConnectTool.Sample
            {
                public partial class Widget
                {
                    public int B;
                    public int C;
                }
            }
            """;

        var sizes = TypeSizeMeasurement.Measure(
        [
            new SourceFile("Widget.cs", first),
            new SourceFile("Widget.Extra.cs", second),
        ]);

        Assert.Equal(9, sizes["ApiConnectTool.Sample.Widget"]);
        Assert.Single(sizes);
    }

    [Fact]
    public void Measure_SeveralTopLevelTypesInOneFile_AttributesLinesToEachType()
    {
        const string source = """
            namespace ApiConnectTool.Sample;

            public enum Kind
            {
                One,
                Two,
            }

            public sealed record Pair(int Left, int Right);

            public class Holder
            {
                private sealed class Nested
                {
                }
            }

            public delegate void Changed(object sender);
            """;

        var sizes = TypeSizeMeasurement.Measure([new SourceFile("Mixed.cs", source)]);

        Assert.Equal(5, sizes["ApiConnectTool.Sample.Kind"]);
        Assert.Equal(1, sizes["ApiConnectTool.Sample.Pair"]);
        Assert.Equal(6, sizes["ApiConnectTool.Sample.Holder"]);
        Assert.Equal(1, sizes["ApiConnectTool.Sample.Changed"]);
        Assert.Equal(4, sizes.Count);
    }

    [Fact]
    public void Measure_SameTypeNameInDifferentNamespaces_IsMeasuredSeparately()
    {
        const string models = """
            namespace ApiConnectTool.Models
            {
                namespace Inner
                {
                    public class Item { }
                }
            }
            """;
        const string views = """
            namespace ApiConnectTool.Views;

            public class Item
            {
            }
            """;

        var sizes = TypeSizeMeasurement.Measure(
        [
            new SourceFile("Models/Item.cs", models),
            new SourceFile("Views/Item.cs", views),
        ]);

        Assert.Equal(1, sizes["ApiConnectTool.Models.Inner.Item"]);
        Assert.Equal(3, sizes["ApiConnectTool.Views.Item"]);
    }

    [Theory]
    [InlineData("Views/MainWindow.axaml.cs")]
    [InlineData("ViewModels/MainWindowViewModel.cs")]
    [InlineData("Program.cs")]
    public void IsHandWritten_AppSourceIncludingCodeBehind_IsMeasured(string path)
    {
        Assert.True(TypeSizeMeasurement.IsHandWritten(new SourceFile(path, "class A { }")));
    }

    [Theory]
    [InlineData("obj/Debug/net10.0/ApiConnectTool.AssemblyInfo.cs")]
    [InlineData("bin/Debug/net10.0/Copied.cs")]
    [InlineData("Views/obj/Stray.cs")]
    [InlineData("Views/MainWindow.g.cs")]
    [InlineData("Views/MainWindow.g.i.cs")]
    [InlineData("Properties/Resources.Designer.cs")]
    [InlineData("Views/MainWindow.axaml")]
    public void IsHandWritten_BuildOutputGeneratedAndMarkupFiles_AreExcluded(string path)
    {
        Assert.False(TypeSizeMeasurement.IsHandWritten(new SourceFile(path, "class A { }")));
    }

    [Fact]
    public void IsHandWritten_AutoGeneratedHeader_IsExcluded()
    {
        const string source = """
            // <auto-generated>
            //     This code was generated by a tool.
            // </auto-generated>
            namespace ApiConnectTool.Sample;

            public class Generated { }
            """;

        Assert.False(TypeSizeMeasurement.IsHandWritten(new SourceFile("Generated.cs", source)));
    }

    [Fact]
    public void MeasureAppProject_FromTestOutput_MeasuresHandWrittenTypesIncludingCodeBehind()
    {
        var sizes = TypeSizeMeasurement.MeasureAppProject();

        Assert.True(sizes["ApiConnectTool.ViewModels.MainWindowViewModel"] > 0);
        Assert.True(sizes["ApiConnectTool.Views.MainWindow"] > 0);
        Assert.DoesNotContain(sizes.Keys, name => name.StartsWith("CompiledAvaloniaXaml", StringComparison.Ordinal));
        Assert.DoesNotContain(sizes.Keys, name => name.StartsWith("ApiConnectTool.Tests", StringComparison.Ordinal));
    }
}
